-- 3. DIM PRODUCT VIEW
CREATE OR REPLACE VIEW VW_DIM_PRODUCTS AS
WITH PRODUCT_DESCRIPTION AS
(
    SELECT
        STOCKCODE,
        DESCRIPTION,
        COUNT(*) AS TRANSACTION_COUNT
    FROM CLEAN_TRANSACTIONS
    GROUP BY STOCKCODE, DESCRIPTION
),
RANKED_PRODUCTS AS
(
    SELECT
        STOCKCODE,
        DESCRIPTION,
        ROW_NUMBER() OVER
        (
            PARTITION BY STOCKCODE
            ORDER BY TRANSACTION_COUNT DESC, DESCRIPTION
        ) AS RN
    FROM PRODUCT_DESCRIPTION
)
SELECT
    STOCKCODE,
    DESCRIPTION
FROM RANKED_PRODUCTS
WHERE RN = 1
ORDER BY STOCKCODE;

-- 4. DIM DATE VIEW
CREATE OR REPLACE VIEW VW_DIM_DATE AS
WITH DATE_RANGE AS
(
    SELECT
        DATEADD(
            DAY,
            SEQ4(),
            (
                SELECT MIN(CAST(INVOICEDATE AS DATE))
                FROM CLEAN_TRANSACTIONS
            )
        ) AS DATE
    FROM TABLE(GENERATOR(ROWCOUNT => 1000))
)
SELECT
    DATE,
    YEAR(DATE) AS YEAR,
    QUARTER(DATE) AS QUARTER,
    MONTH(DATE) AS MONTH_NUMBER,
    MONTHNAME(DATE) AS MONTH_NAME,
    WEEK(DATE) AS WEEK_NUMBER,
    DAY(DATE) AS DAY,
    DAYNAME(DATE) AS DAY_NAME
FROM DATE_RANGE
WHERE DATE <=
(
    SELECT MAX(CAST(INVOICEDATE AS DATE))   
    FROM CLEAN_TRANSACTIONS
)
ORDER BY DATE;

