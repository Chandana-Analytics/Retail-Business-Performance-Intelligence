-- 1. FACT SALES VIEW
CREATE OR REPLACE VIEW VW_FACT_SALES AS
SELECT
    INVOICE,
    STOCKCODE,
    CUSTOMER_ID,
     CAST(INVOICEDATE AS DATE) AS INVOICEDATE,QUANTITY,
    PRICE AS UNIT_PRICE,
    (QUANTITY * PRICE) AS SALES_AMOUNT
    FROM CLEAN_TRANSACTIONS;

-- 2. DIM CUSTOMER VIEW
CREATE OR REPLACE VIEW VW_DIM_CUSTOMERS AS
WITH CUSTOMER_COUNTRY AS
(
    SELECT
        CUSTOMER_ID,
        COUNTRY,
        COUNT(*) AS ORDER_COUNT
    FROM CLEAN_TRANSACTIONS
    GROUP BY CUSTOMER_ID, COUNTRY
),
RANKED_COUNTRIES AS
(
    SELECT
        CUSTOMER_ID,
        COUNTRY,
        ORDER_COUNT,
        ROW_NUMBER() OVER (
            PARTITION BY CUSTOMER_ID
            ORDER BY ORDER_COUNT DESC, COUNTRY
        ) AS RN
    FROM CUSTOMER_COUNTRY
)
SELECT
    CUSTOMER_ID,
    COUNTRY
FROM RANKED_COUNTRIES
WHERE RN = 1
ORDER BY CUSTOMER_ID;

